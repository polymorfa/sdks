import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const source = fs.readFileSync(new URL("../app/wwwroot/native-bridge.js", import.meta.url), "utf8").replaceAll("export function", "function");
const forwarded = [];
const bridged = [];
const context = vm.createContext({ URL, Request, Response, DOMException, location: { href: "https://0.0.0.1/", origin: "https://0.0.0.1" }, fetch: async (...args) => { forwarded.push(args); return new Response("{}"); } });
vm.runInContext(source + ";globalThis.testInstall=install;globalThis.testDispose=dispose", context);
context.testInstall({ invokeMethodAsync: async (_, action) => { bridged.push(action); return { status: 200, body: "{}", contentType: "application/json" }; } });
assert.equal((await context.fetch("/api/polymorfa/token", { method: "POST", headers: { Origin: "https://evil.example", Cookie: "stolen" }, body: '{"session":"foreign"}' })).status, 200);
assert.equal(bridged.join(","), "token");
assert.equal((await context.fetch("/api/polymorfa/token")).status, 405);
await context.fetch("https://api.polymorfa.com/messaging/support/status", { headers: { Authorization: "Bearer pmfa_ct_Zml4dHVyZQ" } });
assert.equal(forwarded.length, 1);
await context.fetch("/api/polymorfa/token?session=foreign", { method: "POST" });
assert.equal(bridged.length, 1);
const abort = new AbortController(); abort.abort();
await assert.rejects(context.fetch("/example/config", { signal: abort.signal }), { name: "AbortError" });
await context.fetch("app://evil.example/api/polymorfa/token", { method: "POST" });
assert.equal(bridged.length, 1);
context.testDispose(); await context.fetch("/example/config");
assert.equal(forwarded.length, 4);
context.location.href = "app://0.0.0.1/"; context.location.origin = "null";
context.testInstall({ invokeMethodAsync: async (_, action) => { bridged.push(action); return {status: 200, body: "{}", contentType: "application/json"}; } });
await context.fetch("/example/config"); assert.equal(bridged.at(-1), "config");
await context.fetch("app://evil.example/api/polymorfa/token", {method: "POST"}); assert.equal(bridged.at(-1), "config");
context.testDispose();
console.log("Actual bridge module route/method/header/body isolation, cancellation and disposal checks passed.");
