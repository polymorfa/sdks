package polymorfa

// KnownErrorCodes returns an independent copy of the stable API error catalog.
// Error.Code continues to preserve arbitrary new codes returned by the API.
func KnownErrorCodes() []string { return append([]string(nil), knownErrorCodes[:]...) }

// IsKnownErrorCode reports whether code is in the pinned API catalog.
func IsKnownErrorCode(code string) bool {
	for _, value := range knownErrorCodes {
		if code == value {
			return true
		}
	}
	return false
}

